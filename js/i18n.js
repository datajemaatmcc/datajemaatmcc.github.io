const KEY = "cms_lang";

/** Bahasa aktif saat ini. */
export function getLang() {
  const v = localStorage.getItem(KEY);
  return v === "en" ? "en" : "id";
}

/** Ganti bahasa lalu muat ulang penerapan teks. */
export function setLang(lang) {
  localStorage.setItem(KEY, lang === "en" ? "en" : "id");
  document.documentElement.lang = getLang();
}

/** Terjemahan sederhana: t("menu.dashboard"). Kunci hilang → kunci itu sendiri. */
export function t(key) {
  const lang = getLang();
  return (DICT[lang] && DICT[lang][key]) || DICT.id[key] || key;
}

/** Terapkan teks ke semua elemen ber-label data-i18n. */
export function applyI18n(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
}
